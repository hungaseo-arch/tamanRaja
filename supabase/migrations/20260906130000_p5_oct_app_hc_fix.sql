-- 2026-10 당월핸디를 규칙(기준핸디 복귀 후 초기화)대로 맞춘다.
--
-- 20260906121804 는 7월을 조 변경 달로 보고 정기혁·정재욱·조학영을 잘못
-- 고쳤다. 7월은 전 회원 기준핸디를 새로 정한 달이라 초기화 상태였고, 저장된
-- 7~9월 차월핸디는 이 규칙과 모두 일치한다(검산). 어긋난 것은 9월 → 10월뿐:
-- 8월 조 변경으로 9월 당월핸디가 기준핸디로 복귀한 회원은 9월에 직전 조와
-- 견주지 않고 9월 결과만으로 ±1 해야 한다.
--
--   고영춘 17→18 · 김재헌 14→13 · 서종환 13→12 · 유영보 15→14
--   정기혁 22→23 · 정재욱 20→21 · 조학영 18→17 (원복)
with fix(ym, name, app_hc) as (values
  ('2026-10', '고영춘', 18),
  ('2026-10', '김재헌', 13),
  ('2026-10', '서종환', 12),
  ('2026-10', '유영보', 14),
  ('2026-10', '정기혁', 23),
  ('2026-10', '정재욱', 21),
  ('2026-10', '조학영', 17)
)
update monthly_handicaps mh
set app_hc = f.app_hc
from fix f
join members m on m.name = f.name
where mh.member_id = m.id and mh.year_month = f.ym;

-- 2026-07 특례 오적용으로 어긋난 핸디 보정 (20260906000100 규칙 수정의 후속)
--
-- 2026-07 은 기준 핸디를 새로 적용한 달이라 예전 로직이 1월 특례로 취급해
-- 조가 바뀐 회원까지 ±1 했다. 규칙표대로면 그 달에 조가 바뀐 회원은 새
-- 기준 핸디로 복귀했어야 하고, 그 차이가 8월·9월 당월핸디를 거쳐 10월까지
-- 그대로 흘러갔다.
--
-- 아래 값은 수정된 규칙으로 2026-07 → 10 을 다시 계산한 결과다. 8월·9월의
-- 조 편성과 시상(Winner·Medalist·Host)은 재계산해도 한 명도 바뀌지 않는다
-- (검산 완료). 그래서 meeting_results 는 건드리지 않고 핸디 값만 맞춘다.
--
--   정기혁 10월 당월핸디 23 → 22 · 정재욱 21 → 20 · 조학영 17 → 18

with fix(ym, name, app_hc, next_hc) as (values
  -- 2026-07: 조가 바뀐 회원은 기준 핸디로 복귀
  ('2026-07', '박영진', null::int, 10),
  ('2026-07', '서종환', null,      13),
  ('2026-07', '유영보', null,      15),
  ('2026-07', '정기혁', null,      20),
  ('2026-07', '정인원', null,      12),
  ('2026-07', '정재욱', null,      18),
  ('2026-07', '조학영', null,      19),
  -- 2026-08: 7월 차월핸디 승계 + 그 달 결과로 재산출
  ('2026-08', '박영진', 10, 10),
  ('2026-08', '서종환', 13, 13),
  ('2026-08', '유영보', 15, 15),
  ('2026-08', '정기혁', 20, 21),
  ('2026-08', '정인원', 12, 11),
  ('2026-08', '정재욱', 18, 19),
  ('2026-08', '조학영', 19, 18),
  -- 2026-09
  ('2026-09', '정기혁', 21, 22),
  ('2026-09', '정인원', 11, 12),
  ('2026-09', '정재욱', 19, 20),
  ('2026-09', '조학영', 18, 18),
  -- 2026-10: 아직 치르지 않은 달이라 당월핸디만
  ('2026-10', '정기혁', 22, null),
  ('2026-10', '정재욱', 20, null),
  ('2026-10', '조학영', 18, null)
)
update monthly_handicaps mh
set app_hc  = coalesce(f.app_hc,  mh.app_hc),
    next_hc = coalesce(f.next_hc, mh.next_hc)
from fix f
join members m on m.name = f.name
where mh.member_id = m.id and mh.year_month = f.ym;
